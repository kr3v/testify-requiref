package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"sort"
	"strings"
)

// renderFile emits either the package-level constructors or the Assertions[T] methods.
//
// Only generic checks get a Assertions[T] method: a concrete-hole check such as
// NoError already produces a fully determined GenericAssertionFunc[error], so binding a
// subject type adds nothing and would just be a T the method ignores.
func renderFile(fns []fn, forMethods bool) []byte {
	var body bytes.Buffer
	imports := map[string]bool{"github.com/stretchr/testify/require": true}

	for _, f := range fns {
		// Only generic checks get a Assertions[T] method. A concrete-hole check such
		// as NoError already yields a fully determined GenericAssertionFunc[error], so a bound
		// subject type would just be a T the method ignores.
		if forMethods && !f.generic {
			continue
		}
		for _, p := range f.params {
			if i := importFor(p.typ); i != "" {
				imports[i] = true
			}
		}
		body.WriteString(emit(f, forMethods))
		body.WriteString("\n")
	}

	var head bytes.Buffer
	head.WriteString("// Code generated by internal/gen. DO NOT EDIT.\n\n")
	head.WriteString("package require\n\nimport (\n")
	var std, ext []string
	for i := range imports {
		if strings.Contains(strings.SplitN(i, "/", 2)[0], ".") {
			ext = append(ext, i)
		} else {
			std = append(std, i)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)
	for _, i := range std {
		fmt.Fprintf(&head, "\t%q\n", i)
	}
	if len(std) > 0 && len(ext) > 0 {
		head.WriteString("\n")
	}
	for _, i := range ext {
		fmt.Fprintf(&head, "\t%q\n", i)
	}
	head.WriteString(")\n\n")
	head.Write(body.Bytes())

	out, err := format.Source(head.Bytes())
	if err != nil {
		log.Fatalf("formatting generated source: %v\n%s", err, head.String())
	}
	return out
}

func importFor(typ string) string {
	switch {
	case strings.Contains(typ, "assert."):
		return "github.com/stretchr/testify/assert"
	case strings.Contains(typ, "time."):
		return "time"
	case strings.Contains(typ, "http."):
		return "net/http"
	case strings.Contains(typ, "url."):
		return "net/url"
	}
	return ""
}

func emit(f fn, method bool) string {
	subject := f.params[f.hole].typ
	if f.generic {
		subject = "T"
	}

	// bound params: everything except the hole, in declaration order.
	// Parameters that are the same type as the subject are typed T rather than
	// left as any -- that is the safety testify's interface{} signatures lose.
	var bound []string
	for i, p := range f.params {
		if i == f.hole {
			continue
		}
		typ := p.typ
		if f.generic && (typ == "interface{}" || typ == "any") && bindsToT(f.name, p.name) {
			typ = "T"
		}
		bound = append(bound, p.name+" "+typ)
	}
	bound = append(bound, "msgAndArgs ...any")

	// forwarded argument list, with the hole filled by `actual`
	var fwd []string
	for i, p := range f.params {
		if i == f.hole {
			fwd = append(fwd, "actual")
			continue
		}
		fwd = append(fwd, p.name)
	}

	var b strings.Builder
	if f.doc != "" {
		b.WriteString(f.doc + "\n")
	}
	switch {
	case method:
		fmt.Fprintf(&b, "func (Assertions[T]) %s(%s) %s {\n", f.name, strings.Join(bound, ", "), f.ret)
	case f.generic:
		fmt.Fprintf(&b, "func %s[T any](%s) %s {\n", f.name, strings.Join(bound, ", "), f.ret)
	default:
		fmt.Fprintf(&b, "func %s(%s) %s {\n", f.name, strings.Join(bound, ", "), f.ret)
	}
	b.WriteString("\tloc := loc()\n")
	fmt.Fprintf(&b, "\treturn func(t TestingT, actual %s, called ...any) {\n", subject)
	// inlined rather than a helper call: Helper() marks its own caller, so it
	// has to run in the closure frame -- the same reason testify inlines it.
	b.WriteString("\t\tif h, ok := t.(tHelper); ok {\n\t\t\th.Helper()\n\t\t}\n")
	fmt.Fprintf(&b, "\t\trequire.%s(t, %s, declaredAt(loc, msgAndArgs, called)...)\n", f.name, strings.Join(fwd, ", "))
	b.WriteString("\t}\n}\n")
	return b.String()
}

// bindsToT reports whether a bound parameter shares the subject's type.
func bindsToT(fnName, paramName string) bool {
	if paramName == "expected" {
		return !looseExpected[fnName]
	}
	for _, n := range bindToT[fnName] {
		if n == paramName {
			return true
		}
	}
	return false
}
